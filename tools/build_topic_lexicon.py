def main():
    topics = []
    for name, als in CONCEPTS:
        topics.append({"name": name, "type": "INDUSTRY", "category": "概念",
                       "aliases": sorted({a for a in als if a and a != name})})
    for name, als in INDICES:
        topics.append({"name": name, "type": "INDEX", "category": "指数",
                       "aliases": sorted({a for a in als if a and a != name})})
    with open(TOPIC_PATH, "w", encoding="utf-8") as f:
        for t in topics:
            f.write(json.dumps(t, ensure_ascii=False) + "\n")
    print(f"topic_lexicon: {len(topics)} 条 -> {TOPIC_PATH}")

    # 读现有词表
    entries: dict = {}
    with open(GAZ_PATH, encoding="utf-8") as f:
        for line in f:
            if line.strip():
                e = json.loads(line)
                entries[e["eid"]] = e
    by_norm = {}
    for e in entries.values():
        by_norm.setdefault(_norm_linker(e["name"]), e)
        for a in e.get("aliases", []):
            by_norm.setdefault(_norm_linker(a), e)

    n_new, n_merge, n_alias = 0, 0, 0

    def add_alias(e, alias):
        nonlocal n_alias
        n = _norm_linker(alias)
        if not n or n in by_norm:
            return
        if alias not in e.setdefault("aliases", []):
            e["aliases"].append(alias)
            by_norm[n] = e
            n_alias += 1

    for t in topics:
        anchor = by_norm.get(_norm_linker(t["name"]))
        if anchor and anchor["type"] == t["type"]:
            n_merge += 1
        else:
            anchor = {"eid": eid_of(t["name"]), "name": t["name"], "aliases": [],
                      "type": t["type"], "source": "topic_seed",
                      "meta": {"category": t["category"]}}
            entries[anchor["eid"]] = anchor
            by_norm[_norm_linker(anchor["name"])] = anchor
            n_new += 1
        anchor.setdefault("meta", {})["category"] = t["category"]
        for a in t["aliases"]:
            add_alias(anchor, a)

    # 行业别名补充（只挂既有条目，不新建）
    for name, als in INDUSTRY_ALIASES.items():
        anchor = by_norm.get(_norm_linker(name))
        if anchor and anchor["type"] == "INDUSTRY":
            for a in als:
                add_alias(anchor, a)

    with open(GAZ_PATH, "w", encoding="utf-8") as f:
        for e in sorted(entries.values(), key=lambda x: x["eid"]):
            f.write(json.dumps(e, ensure_ascii=False) + "\n")
    print(f"gazetteer: total {len(entries)} | topic new {n_new} merge {n_merge} alias +{n_alias}")
    n = sync_jieba()
    print(f"jieba user dict: +{n} words")


if __name__ == "__main__":
    main()
